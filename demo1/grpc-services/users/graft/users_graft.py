"""Graftcode facade for the Users service.

Public static methods are the contract hosted by Graftcode Gateway (gg).
They wrap the existing gRPC servicer in ../server/server.py, so the
domain logic is unchanged; only the transport moves from gRPC to Graftcode.
"""
import importlib.util as _importlib_util
import os as _os
from dataclasses import dataclass
from types import SimpleNamespace as _SimpleNamespace

import users_types_pb2 as _messages  # generated by protos/build.sh (on PYTHONPATH)

# Existing gRPC servicer (domain logic): ../server/server.py. Override with USERS_SERVER_PY.
_SERVER_PY = _os.environ.get("USERS_SERVER_PY") or _os.path.join(
    _os.path.dirname(_os.path.abspath(__file__)), "..", "server", "server.py")
_servicer_instance = None


def _servicer():
    global _servicer_instance
    if _servicer_instance is None:
        spec = _importlib_util.spec_from_file_location("users_grpc_server", _SERVER_PY)
        module = _importlib_util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _servicer_instance = module.UsersService()
    return _servicer_instance


@dataclass
class User:
    username: str = ""
    user_id: int = 0


def _context():
    """Feeds Graftcode request headers to the servicer as gRPC-style invocation metadata."""
    def invocation_metadata():
        try:
            from graftcode.context import RequestContext
            return list((RequestContext.current().get_headers() or {}).items())
        except Exception:
            return []
    return _SimpleNamespace(invocation_metadata=invocation_metadata)


class Users:
    @staticmethod
    def create_user(username: str, password: str, email: str) -> User:
        request = _messages.CreateUserRequest(username=username, password=password, email=email)
        result = _servicer().CreateUser(request, _context())
        return User(username=result.user.username, user_id=result.user.user_id)

    @staticmethod
    def get_users(usernames: list[str], user_ids: list[int]) -> list[User]:
        # Parallel primitive lists: gg 1.4.2's Python host cannot yet receive an array of DTOs
        # as a parameter ("has no attribute 'User[]'"); returning list[User] works.
        request = _messages.GetUsersRequest(
            user=[_messages.User(username=n, user_id=i) for n, i in zip(usernames, user_ids)]
        )
        return [
            User(username=r.user.username, user_id=r.user.user_id)
            for r in _servicer().GetUsers(request, _context())
        ]
